    async def read_attachments(self, issue_external_id: int, attachments: list[Any]) -> str:
        """Download + extract text from extractable attachments, concatenated."""
        from app.services import attachment_reader

        parts: list[str] = []
        for a in attachments:
            name = getattr(a, "attachment_file_name", None) or ""
            if not attachment_reader.is_extractable(name):
                continue
            try:
                result = await self._okdesk.download_attachment(issue_external_id, a.id)
                if not result:
                    continue
                # OCR/парсинг — CPU-bound и синхронный; в потоке, чтобы не
                # блокировать единственный event loop uvicorn (иначе весь сервис
                # висит на время разбора).
                text = await asyncio.to_thread(attachment_reader.extract_text, name, result[0])
                if text.strip():
                    parts.append(f"=== Вложение: {name} ===\n{text}")
            except Exception:  # pragma: no cover - best effort
                log.warning("attachment_read_failed", issue=issue_external_id, name=name)
        return "\n\n".join(parts)

    async def _resolve_alt_plate(self, current: str | None, text: str) -> str | None:
        """Среди распознанных в тексте гос.номеров вернуть первый, КОТОРЫЙ ЕСТЬ в
        гео (кроме current). Для случаев, когда номер из темы неточный/опечатка, а
        в теле есть валидный (64655: Х871НХ→Т871НХ64). Best-effort, вызывается
        только когда объект по основному номеру не найден."""
        try:
            cands = extract_all_plates(text)
        except Exception:
            return None
        seen: set[str] = set()
        for p in cands:
            if not p or p == current or p in seen:
                continue
            seen.add(p)
            try:
                obj = await self._geo.find_object_by_plate(p)
                # Только ТОЧНОЕ совпадение в гео: fuzzy-спасение для АЛЬТЕРНАТИВНОГО
                # кандидата — двойная неточность, легко подменяет чужое ТС.
                if obj and not obj.get("fuzzy_plate_match"):
                    return p
            except Exception:  # pragma: no cover - geo may fail
                continue
        return None

    async def automate(self, title: str | None, description: str | None,
                       params: list[dict[str, Any]] | None = None,
                       issue_type: str | None = None,
                       attachments_text: str | None = None,
                       sender: dict[str, Any] | None = None,
                       comments: str | None = None,
                       examples: list[dict[str, Any]] | None = None,
                       example_provider: Callable[
                           [str, str | None, list[str]],
                           Awaitable[list[dict[str, Any]]],
                       ] | None = None,
                       plate_override: str | None = None,
                       date_override: str | None = None,
                       created_at: str | _dt.date | None = None,
                       client_comments: list[tuple[str, str]] | None = None,
                       ) -> AutomationResult:
        # 64871: у форвард-писем description пуст — тело письма лежит в ПЕРВОМ
        # комментарии; добавляем дайджест комментариев к тексту для парсинга
        # (без ISO-таймштампов публикации — см. _scrub_iso_dates).
        parse_extra = attachments_text
        if comments and not _strip_html(description).strip():
            parse_extra = _extra_with_comments(attachments_text, comments)
        parsed = self.parse_issue(title, description, params, extra_text=parse_extra,
                                  created_at=created_at)
        # Дату неисправности добираем ТОЛЬКО из слов клиента и только не позже его
        # сообщения (65781: «27.07 питание восстановлено» в НАШЕМ ответе поддержки
        # становилось датой неисправности). Модель ниже по-прежнему видит полный
        # дайджест переписки (comments) — фильтр касается только разбора дат.
        comments_for_dates = (_client_comments_text(client_comments)
                              if client_comments is not None else comments)
        if comments_for_dates and not parsed.date:
            # Дату клиент дописал КОММЕНТАРИЕМ, а описание при этом не пустое
            # (65780: «по спидометру 90км» в теле, «Извините, что не написала
            # дату. за 22.07.226г» — в комментарии) — ветка выше комментарии не
            # подмешивала, и разбор отдавал date=None. Комментарии тут ТОЛЬКО
            # добирают ПУСТУЮ дату: в переписке дат много (ответ оператора,
            # сроки), перебивать ими дату из темы/тела нельзя.
            alt = self.parse_issue(
                title, description, params,
                extra_text=_extra_with_comments(parse_extra, comments_for_dates),
                created_at=created_at)
            if alt.date:
                parsed.date, parsed.date_to = alt.date, alt.date_to
        # Ручное переопределение (оператор): клиент указал номер с опечаткой,
        # совпавшей с чужим реальным ТС, или неверную дату — авто-разбор тут
        # бессилен. Перезаписываем даже то, что нашёл regex, и пропускаем
        # LLM-fallback для переопределённого поля.
        if plate_override:
            norm = _normalize_plate(plate_override)
            parsed.plate = norm or plate_override.strip()
        if date_override:
            parsed.date = date_override.strip()  # ожидается формат YYYY-MM-DD
        # Fallback: если regex не нашёл гос.номер ИЛИ дату — просим LLM извлечь
        # поля из текста/вложений (нестандартные форматы дочерних Россетей).
        # Не тратим токены, когда regex справился (или поле задано вручную).
        if (not parsed.plate or not parsed.date) and (title or description or attachments_text or comments):
            try:
                body = _strip_html(description)
                if not body.strip() and comments:
                    body = _scrub_iso_dates(comments)[:4000]
                ext = await self._extract_with_llm(title, body, attachments_text)
                self._apply_llm_extraction(parsed, ext)
            except Exception:  # pragma: no cover - best effort
                log.warning("llm_extract_failed", title=(title or "")[:60])

        # Правила разбора особых заявок (см. память project-overdue-rules):
        #  • «ложный wait» — клиент подтвердил питание/работу ТС и ждёт удалённой
        #    диагностики (наш шаблон исчерпан, мяч на нашей стороне);
        #  • спецтехника — без км-пробега, км-вердикт ненадёжен.
        _body_for_spec = f"{title or ''} {_strip_html(description)} {attachments_text or ''}"
        # Тема и описание — наравне с комментариями: «требуется удалённая
        # диагностика» часто стоит прямо в теме заявки (66015). Вложения НЕ
        # отдаём: там шаблонные акты, а не позиция клиента.
        awaiting_diag = _client_awaiting_remote_diag(
            comments, title, _strip_html(description))
        spec = _is_special_vehicle(parsed.plate, _body_for_spec)
        directive_lines: list[str] = []
        if awaiting_diag:
            directive_lines.append(
                "ВАЖНО: клиент уже подтвердил питание/массу/работу ТС и ждёт "
                "УДАЛЁННОЙ диагностики. НЕ повторяй шаблон про включение питания. "
                "Дай результат удалённой диагностики по данным телеметрии за дату; "
                "если данных нет / терминал не выходит на связь — рекомендуй ВЫЕЗД "
                "сервисной бригады.")
        if spec:
            directive_lines.append(
                "ВАЖНО: это СПЕЦТЕХНИКА (трактор/погрузчик/буровая и т.п.) без "
                "обычного км-пробега. НЕ делай вывод о расхождении по километрам; "
                "оценивай факт работы/выхода на связь, при необходимости — моточасы.")
        comments_llm = (("\n".join(directive_lines) + "\n\n" + (comments or "")).strip()
                        if directive_lines else comments)

        def _finalize(res: AutomationResult) -> AutomationResult:
            res.needs_remote_diagnostics = awaiting_diag
            res.spec_vehicle = spec
            notes: list[str] = []
            if awaiting_diag:
                notes.append("⚠ Требуется удалённая диагностика: клиент подтвердил "
                             "питание/работу ТС — не ждать клиента; при отсутствии "
                             "данных назначить выезд бригады.")
            if spec:
                notes.append("⚠ Спецтехника без км-пробега — оценивать по факту "
                             "работы/моточасам, км-расхождение неинформативно.")
            if notes:
                res.reasoning = " ".join(notes) + ("\n" + res.reasoning if res.reasoning else "")
                res.needs_review = True
            res.auto_eligible = (
                (not res.needs_review)
                and res.confidence >= 0.8
                and res.category in ("Глушение", "Данные верны")
                and bool(res.parsed.plate)
                and bool(res.parsed.date)
            )
            return res

        telemetry = TelemetryFacts()
        # No plate, or no fault date → the mileage path can't proceed. Instead of
        # a dead-end error, hand off to the GENERAL ASSISTANT path: the AI reads
        # the issue, names the missing data and drafts an answer / operator note.
        is_mileage = bool(issue_type and "пробег" in issue_type.lower())
        if not parsed.plate or not parsed.date:
            # If the type is explicitly non-mileage, the general path is the right
            # home regardless; if it's mileage but unparseable, still go general.
            return _finalize(await self._draft_general(title, description, attachments_text, sender,
                                                       comments_llm, created_at))
        # A non-mileage issue type that happens to carry a plate still belongs to
        # the general path — the mileage analysis below would be meaningless.
        if issue_type and not is_mileage:
            return _finalize(await self._draft_general(title, description, attachments_text, sender,
                                                       comments_llm, created_at))
        try:
            telemetry = await self.gather_telemetry(parsed.plate, parsed.date, parsed.date_to)
        except Exception:  # pragma: no cover - network errors
            # Telemetry/object lookup failed — fall through to the general path
            # rather than a hard error, so the operator still gets a draft.
            log.exception("gather_telemetry_failed", plate=parsed.plate)
            return _finalize(await self._draft_general(title, description, attachments_text, sender,
                                                       comments_llm, created_at))
        if "object_not_found" in telemetry.flags:
            # Номер из ТЕМЫ мог быть неточным/опечаткой (64655: «Х871НХ» в теме vs
            # «Т871НХ64» в теле — в гео есть второй). Пробуем другие распознанные
            # номера и берём первый, который реально находится в гео.
            alt = await self._resolve_alt_plate(
                parsed.plate, f"{title or ''} {_strip_html(description)} {attachments_text or ''}")
            if alt and alt != parsed.plate:
                parsed.plate = alt
                try:
                    telemetry = await self.gather_telemetry(parsed.plate, parsed.date, parsed.date_to)
                except Exception:  # pragma: no cover
                    log.exception("gather_telemetry_failed", plate=parsed.plate)
                    return _finalize(await self._draft_general(title, description, attachments_text, sender,
                                                               comments_llm, created_at))
            if "object_not_found" in telemetry.flags:
                # Plate parsed but no matching object in Geo: general path can still
                # understand the request and tell the operator what to verify.
                return _finalize(await self._draft_general(title, description, attachments_text, sender,
                                                           comments_llm, created_at))

        # Переоткрытие заявки: если комментарий вводит НОВУЮ дату неисправности
        # (свежее даты тела), анализируем ИМЕННО ЕЁ — дата тела уже была отвечена
        # (64228: решили за 16.06, затем открыли заново «За 24.06 пробег не
        # выгрузился. Прошу возобновить заявку»). Делаем свежую дату ОСНОВНОЙ:
        # переснимаем телеметрию, и весь дальнейший разбор идёт по ней.
        # Ищем новую дату ТОЛЬКО в словах клиента (comments_for_dates): дата из
        # нашего же ответа поддержки не может переопределить дату неисправности.
        _fresh = _scan_comment_for_new_date(comments_for_dates, parsed.date)
        if _fresh and _fresh != parsed.date:
            try:
                ct0 = await self.gather_telemetry(parsed.plate, _fresh)
                if "object_not_found" not in ct0.flags:
                    parsed.date = _fresh
                    parsed.date_to = None
                    telemetry = ct0
            except Exception:  # pragma: no cover - best effort
                log.warning("comment_date_reanalyze_failed",
                            plate=parsed.plate, date=_fresh)

        hint = self._heuristic_category(parsed, telemetry)
        # RAG: fetch similar past resolved cases as few-shot examples. The
        # provider is category-aware (hint computed above), so retrieval is
        # targeted. Best-effort: any failure proceeds without examples.
        if examples is None and example_provider is not None:
            try:
                examples = await example_provider(hint, parsed.plate, telemetry.flags)
            except Exception:  # pragma: no cover - best effort, never break automate
                log.warning("example_provider_failed", plate=parsed.plate)
                examples = None
        # IMPROVEMENT 1 (64201): if the fault date shows power-off/no-data AND
        # there are comments (possibly claiming a fix), verify against real data
        # whether anything actually resumed after the fault date. Bounded to one
        # extra daily-stats call; any failure omits the fact (never breaks).
        # Обрыв данных среди дня (64275): данные за дату БЫЛИ, но прекратились рано
        # (последний пакет до 17:00 МСК) и не возобновились до конца суток —
        # признак потери питания/связи в течение рабочего дня.
        midday_stop = bool(
            telemetry.packets
            and telemetry.tail_gap_min and telemetry.tail_gap_min > 240
            and telemetry.last_packet_msk and telemetry.last_packet_msk < "17:00"
        )
        verify_resumed: dict[str, Any] | None = None
        if (telemetry.object_id is not None
                and ("power_off" in telemetry.flags or "no_data" in telemetry.flags or midday_stop)):
            # Запускаем и без комментариев: это вход в детерминированную ветку
            # «нет данных/обрыв за дату → возобновились ли они позже» (алгоритм ниже).
            verify_resumed = await self._verify_data_resumed(
                telemetry.object_id, parsed.date)

        # IMPROVEMENT 2 (63301): if a comment introduces a NEW date+mileage that
        # differs from the body's fault date, gather telemetry for that date too
        # and pass it as a fact so the LLM answers by the freshest comment date.
        comment_date_facts: dict[str, Any] | None = None
        comment_date = _scan_comment_for_new_date(comments_for_dates, parsed.date)
        if comment_date:
            try:
                ct = await self.gather_telemetry(parsed.plate, comment_date)
                comment_date_facts = {
                    "дата": comment_date,
                    "реальный_пробег_системы_км": ct.system_mileage_km,
                    "пакетов_телеметрии": ct.packets,
                    "признаки": ct.flags,
                    "телепортов_трека": ct.teleport_jumps,
                    "доля_слабого_сигнала": ct.low_sat_ratio,
                    "доля_без_питания": ct.power_off_ratio,
                }
            except Exception:  # pragma: no cover - never break automate
                log.warning("comment_date_telemetry_failed",
                            plate=parsed.plate, date=comment_date)

        llm = await self._draft_with_llm(
            parsed, telemetry, hint,
            attachments_text=attachments_text, sender=sender, examples=examples,
            comments=comments_llm,
            verify_resumed=verify_resumed,
            comment_date_facts=comment_date_facts,
        )
        category = llm.get("category") or hint
        # Источник вердикта: категорию назвал LLM или (пустой ответ модели) она
        # осталась детерминированной эвристикой. Фронт показывает это явно.
        verdict_source = "ai" if llm.get("category") else "rules"
        draft = _clean_answer(llm.get("answer") or "")
        confidence = float(llm.get("confidence") or 0.0)
        reasoning = llm.get("reasoning") or ""
        if not draft:
            # fallback to catalog template
            tpl = next((c for c in _CATEGORY_CATALOG if c["key"] == category), _CATEGORY_CATALOG[0])
            draft = tpl["template"].format(
                date=parsed.date or "",
                system_km=telemetry.system_mileage_km if telemetry.system_mileage_km is not None else "",
            )
            confidence = confidence or 0.4
            reasoning = reasoning or f"Эвристика: {hint}"
        # Large under-recording (system << waybill) means the snapshot may be
        # incomplete (delayed black-box upload) — always send to review and
        # cap confidence, no matter how sure the model sounded.
        under_recording = (
            parsed.sheet_mileage_km
            and telemetry.system_mileage_km is not None
            and telemetry.system_mileage_km < parsed.sheet_mileage_km * 0.7
        )
        if under_recording:
            confidence = min(confidence, 0.7)
        # «Терминал подключился» при разрыве трека ненадёжен (~27% точности по данным
        # операторов): чаще это глушение. Всегда отправляем на проверку оператором.
        force_review = category == "Терминал подключился"
        return _finalize(AutomationResult(
            parsed=parsed, telemetry=telemetry, category=category,
            confidence=min(confidence, 0.6) if force_review else confidence,
            draft_answer=draft, reasoning=reasoning,
            needs_review=confidence < 0.85 or bool(under_recording) or force_review,
            verdict_source=verdict_source, heuristic_category=hint,
        ))

    async def build_track(self, title: str | None, description: str | None,
                          max_points: int = 2500, attachments_text: str | None = None,
                          plate: str | None = None, fault_date: str | None = None,
                          date_from: str | None = None, date_to: str | None = None,
                          created_at: str | _dt.date | None = None) -> dict[str, Any]:
        """Return track points + telemetry series for map/charts rendering.

        Points: {t(ms), lat, lng, speed, sat, pwr}. ``teleports`` are indices i
        where the jump from point i-1 to i is physically impossible (GPS spoofing).
        ``plate``/``fault_date`` override parsing (per-object track из разбора).
        ``date_from``/``date_to`` (YYYY-MM-DD) задают произвольный интервал.
        """
        if plate and fault_date:
            parsed = ParsedIssue(plate=plate, date=fault_date)
        else:
            parsed = self.parse_issue(title, description, None,
                                      extra_text=attachments_text, created_at=created_at)
        if not parsed.plate or not parsed.date:
            # Раздельные коды (64826/64838: номер в теме ЕСТЬ, нет только даты —
            # сообщение «номер не найден» вводило оператора в заблуждение).
            code = "no_date" if parsed.plate else "no_plate"
            return {"error": code, "parsed": asdict(parsed), "points": []}
        obj = await self._geo.find_object_by_plate(parsed.plate)
        if not obj:
            return {"error": "object_not_found", "parsed": asdict(parsed), "points": []}
        oid = int(obj["id"])
        # Window: explicit interval (capped 31 days) or the single fault day.
        # Поддержка ВРЕМЕНИ: 'YYYY-MM-DD' → границы суток МСК; 'YYYY-MM-DDTHH:MM'
        # (или с пробелом) → точный момент МСК (интервал трека по времени, 3.4).
        def _bound_ms(s: str, end: bool) -> int:
            if "T" in s or " " in s:
                dt = _dt.datetime.fromisoformat(s.replace(" ", "T"))
                return int(dt.replace(tzinfo=_MSK).timestamp() * 1000)
            d = _dt.date.fromisoformat(s)
            a, b = _msk_day_window_ms(d)
            return b if end else a

        try:
            f_raw = date_from or parsed.date
            t_raw = date_to or f_raw
            from_ms = _bound_ms(f_raw, end=False)
            till_ms = _bound_ms(t_raw, end=True)
        except (ValueError, TypeError):
            from_ms, till_ms = _msk_day_window_ms(_dt.date.fromisoformat(parsed.date))
        if till_ms < from_ms:
            from_ms, till_ms = till_ms, from_ms
        _cap = 31 * 86400 * 1000
        if till_ms - from_ms > _cap:
            till_ms = from_ms + _cap
        range_from = _msk_date_from_ms(from_ms).isoformat()
        range_to = _msk_date_from_ms(max(from_ms, till_ms - 1)).isoformat()
        packets = await self._geo.get_packets(oid, from_ms, till_ms)
        packets.sort(key=lambda p: p.get("time") or 0)

        teleports: list[int] = []
        for i in range(1, len(packets)):
            a, b = packets[i - 1], packets[i]
            if not (a.get("lat") and a.get("lng") and b.get("lat") and b.get("lng")):
                continue
            dt = ((b.get("time") or 0) - (a.get("time") or 0)) / 1000.0
            if dt <= 0:
                continue
            impl = _haversine_m(a["lat"], a["lng"], b["lat"], b["lng"]) / dt * 3.6
            if impl > _TELEPORT_KMH:
                teleports.append(i)

        step = max(1, len(packets) // max_points)
        tele_set = set(teleports)
        points: list[dict[str, Any]] = []
        index_map: dict[int, int] = {}
        for i, p in enumerate(packets):
            if i % step != 0 and i not in tele_set:
                continue
            tags = p.get("tags") if isinstance(p.get("tags"), dict) else {}
            index_map[i] = len(points)
            points.append({
                "t": p.get("time"),
                "lat": round(p["lat"], 5) if p.get("lat") else None,
                "lng": round(p["lng"], 5) if p.get("lng") else None,
                "speed": p.get("speed") or 0,
                "sat": p.get("sat") or 0,
                "pwr": round(tags.get("pwr_ext"), 1) if tags.get("pwr_ext") is not None else None,
            })
        # Current object status (online/offline, last fix time) — best effort.
        status: dict[str, Any] = {}
        try:
            st = await self._geo.get_object_status(oid)
            if st is not None:
                status = {
                    "online": st.online,
                    "last_time": st.time,  # unix seconds of last packet
                    "speed": st.speed,
                    "sat": st.sat,
                }
        except Exception:  # pragma: no cover - best effort
            pass

        return {
            "parsed": asdict(parsed),
            "object_id": oid,
            "object_name": obj.get("name"),
            "imei": obj.get("imei"),
            "phone": obj.get("phone") or obj.get("phone1"),
            "status": status,
            "range_from": range_from,
            "range_to": range_to,
            "total_packets": len(packets),
            "points": points,
            "teleports": [index_map[i] for i in teleports if i in index_map],
        }

    # Hard cap on attachments processed per batch. Without it, issues like
    # ОДКРА «письма» (9+ scanned letter-PDFs) trigger minutes of Tesseract OCR
    # per request — the call never returns and the UI shows «Ошибка разбора».
    _BATCH_MAX_ATTACHMENTS = 25
    # Бюджет времени на ОДИН запрос разбора (сервер 1 ядро/1 ГБ — большой
    # многоактный PDF не успевает целиком за окно фронт-таймаута 90 с). Новые
    # вложения перестаём начинать после дедлайна; распознанное копится в кэше
    # (ocr:<att_id>) и дотягивается при следующем «Обновить разбор».
    _BATCH_REQUEST_BUDGET_S = 60.0

    async def analyze_batch(self, issue_external_id: int, attachments: list[Any],
                            issue_title: str | None = None,
                            issue_description: str | None = None,
                            ocr_cache: Any = None,
                            progress_out: dict[str, Any] | None = None,
                            created_at: str | _dt.date | None = None,
                            extra_text: str | None = None,
                            fallback_date: str | None = None,
                            issue_intent: str | None = None) -> list[dict[str, Any]]:
        """Per-object analysis of a batch/«общая» issue (one vehicle act per attachment).

        Returns a list of {file, plate, date, sheet_mileage_km, system_mileage_km,
        flags, teleport_jumps, verdict}. Mass issues are usually jamming, but some
        objects have correct data (system ≈ waybill) and need separate handling.

        ``created_at`` — дата создания заявки, нужна только для года даты
        неисправности (см. parse_issue). Не передали — прежнее поведение.

        ``extra_text`` — тот же дополнительный текст (вложения/дайджест
        комментариев), по которому считалась ШАПКА разбора: без него строки
        таблицы оставались без даты, хотя в шапке дата была. Не передали —
        прежнее поведение.

        ``fallback_date`` — дата из шапки разбора для строк, у которых своей нет.
        Отдельным параметром, а НЕ через ``extra_text``: дату из переписки
        добирать надо (65780), а вот заводить по переписке новое ТС — нельзя.
        Пропустив дайджест комментариев в текст, мы получали строку, где
        гос.номер взят из ответа оператора, а дата — из соседнего комментария про
        ДРУГУЮ машину (65847): телеметрия запрашивалась для чужой пары
        «номер + дата», и вердикт выглядел достоверным, будучи бессмысленным.

        Degrades gracefully: never raises. When there are no extractable
        attachments, OCR yields nothing, or no plates can be parsed, returns
        ``[]`` (the endpoint surfaces a note) instead of propagating an error.
        """
        from app.services import attachment_reader

        created = _created_date(created_at)

        def _parse(t: str | None, body: str | None = "",
                   extra: str | None = None) -> ParsedIssue:
            """parse_issue с датой создания заявки: год даты неисправности
            берётся/прижимается по ней одинаково во ВСЕХ ветках разбора."""
            return self.parse_issue(t, body, None, extra_text=extra, created_at=created)

        # Полные номера (с кодом региона) из ТЕМЫ заявки — по ключу без региона.
        # Тема — самый надёжный источник региона: имя файла и OCR его часто теряют
        # (65259: тема «Нет данных О613ТТ56», вложение «65259_о613тт.jpeg» —
        # разбор отдавал О613ТТ, и оператор терял регион).
        title_region_plates: dict[str, str] = {}
        for _tp in extract_all_plates(issue_title or "", include_special=True):
            if _plate_has_region(_tp):
                title_region_plates.setdefault(_plate_dedup_key(_tp), _tp)

        def _restore_region(
            rows: list[tuple[Any, Any, Any, Any]],
        ) -> list[tuple[Any, Any, Any, Any]]:
            """Достроить регион номерам, у которых его нет, полным номером из ТЕМЫ.
            Единая точка для ВСЕХ целей разбора: и для «номер из имени файла», и
            для табличных/актовых строк. Подменяем только тот же самый ТС —
            совпадение по ``_plate_dedup_key`` (номер без региона)."""
            if not title_region_plates:
                return rows
            out: list[tuple[Any, Any, Any, Any]] = []
            for pl, dt_, s_, g_ in rows:
                if pl and _plate_lacks_region(str(pl)):
                    full = title_region_plates.get(_plate_dedup_key(str(pl)))
                    if full:
                        pl = full
                out.append((pl, dt_, s_, g_))
            return out

        results: list[dict[str, Any]] = []
        try:
            attachments = list(attachments or [])
        except Exception:
            attachments = []

        _head_text = f"{issue_title or ''}\n{_strip_html(issue_description)}"

        def _intent_for(att_text: str | None) -> str | None:
            """Тип заявки для строк ЭТОГО документа. Если вызвавший его уже
            посчитал (parse_facts), берём готовый; иначе определяем сами —
            эндпоинт /automate_batch зовёт analyze_batch напрямую, а у письма-
            заявки вся суть может быть только во вложении."""
            if issue_intent is not None:
                return issue_intent
            lab = _detect_non_mileage_intent(_head_text, att_text)
            if lab is None and _detect_false_mileage(_head_text):
                return FALSE_MILEAGE_INTENT
            return lab

        extractable = [
            a for a in attachments
            if attachment_reader.is_extractable(
                getattr(a, "attachment_file_name", None) or ""
            )
        ]
        # Вложений нет, но в ТЕМЕ/ТЕЛЕ перечислено несколько ТС (Прихоперское ПО,
        # 64455: «…В524ОА…, В191РХ…, А651НМ…»). Раньше такая заявка шла в одиночный
        # automate и анализировался ТОЛЬКО первый номер. Разбираем КАЖДЫЙ номер:
        # дата/пробег берём из общего разбора темы+тела (одна на всех, если своей нет).
        if not extractable:
            # Триггер по ТЕМЕ И ТЕЛУ письма (согласовано с фронтом: countPlates по
            # subject+description). Раньше смотрели только тему — заявки со списком
            # ТС в ТЕЛЕ, а не в теме (65649: тема = дата «01.07.2026», в теле 20
            # номеров построчно) уходили в одиночный automate и теряли всех, кроме
            # первого. Разбираем каждый номер: своя дата/пробег из тела, добор из темы.
            body_rows = _parse_body_vehicles(
                issue_description,
                bare_mileage_ok=(_intent_for(None) == FALSE_MILEAGE_INTENT))  # (plate,date,sheet,glonass)
            body_keys = {_plate_dedup_key(p) for p, _, _, _ in body_rows}
            title_plates = extract_all_plates(issue_title or "")
            # ОДИН объект разбираем ТЕМ ЖЕ движком, что и N (раньше требовалось
            # >= 2 номера, и одиночная заявка возвращала пустой список — факты и
            # предварительный вердикт можно было получить только через LLM-прогон).
            # Порог снят: фронт получает одинаковую таблицу для 1 и для N ТС, не
            # потратив ни одного токена. OCR здесь не запускается — ветка работает
            # только когда извлекаемых вложений нет.
            p0 = _parse(issue_title, issue_description, extra_text)
            # Дата шапки — только если своя не нашлась (см. fallback_date выше).
            p0_date = p0.date or fallback_date
            targets_subj: list[tuple[str, str | None, float | None, float | None]] = list(body_rows)
            # Каждая строка тела — своя цель (своя дата/пробег, 64455/65649).
            # Номера, встреченные только в ТЕМЕ, добираем с общей датой/ПЛ из
            # разбора темы+тела (fallback), чтобы ТС из темы не потерялся.
            for plate in title_plates:
                if _plate_dedup_key(plate) not in body_keys:
                    targets_subj.append(
                        (plate, p0_date, p0.sheet_mileage_km, p0.declared_system_km))
            if not targets_subj and p0.plate:
                # Номер есть только в общем разборе темы+тела (нестандартная
                # разметка строки) — одиночная заявка не должна остаться без строки.
                targets_subj.append(
                    (p0.plate, p0_date, p0.sheet_mileage_km, p0.declared_system_km))
            # ОБЩАЯ дата заявки — строкам, у которых СВОЕЙ даты нет. 65910: в
            # сводном разборе дата 23.07 и ПЛ есть, а обе строки объектов вышли
            # с date=None → «Нет номера/даты» и телеметрия не запрашивалась
            # вообще. Раньше добор общей даты был только у номеров из ТЕМЫ, а
            # строки тела оставались без даты при любом их количестве.
            # Своя дата (из своей строки/акта) ПРИОРИТЕТНЕЕ и не перебивается:
            # у одного ТС за разные даты — разные вердикты (63617).
            # Пробеги НЕ раздаём: дата у заявки одна на всех, а пробег у каждого
            # ТС свой — общий ПЛ, размноженный по строкам, дал бы ложные вердикты.
            if p0_date:
                targets_subj = [(pl, dt or p0_date, s, g)
                                for pl, dt, s, g in targets_subj]
            # Регион номера — из темы (см. _restore_region).
            targets_subj = _restore_region(targets_subj)
            # Год строк тела прижимаем к дате создания — см. такой же кламп для
            # табличных/актовых строк ниже.
            if created is not None:
                targets_subj = [(pl, _clamp_year_to_created(dt, created), s, g)
                                for pl, dt, s, g in targets_subj]
            if targets_subj:
                sem0 = asyncio.Semaphore(_BATCH_CONCURRENCY)

                async def _one_subj(plate: str, pdate: str | None, psheet: float | None,
                                    pglonass: float | None) -> dict[str, Any] | None:
                    async with sem0:
                        try:
                            return await self._analyze_object(
                                plate, pdate, psheet, None, "(из текста заявки)",
                                declared=pglonass, intent=_intent_for(None))
                        except Exception:
                            log.warning("analyze_batch_subject_failed", plate=plate)
                            return None

                chunk0 = await asyncio.gather(
                    *(_one_subj(p, d, s, g) for p, d, s, g in targets_subj))
                return [r for r in chunk0 if r is not None]
        # Возобновляемое извлечение текста с накоплением в кэше (ocr:<att_id>):
        # распознанное вложение не гоняется повторно, большой скан дотягивается за
        # несколько запросов. Дедлайн запроса не даёт начать новую тяжёлую OCR-работу
        # после исчерпания бюджета — частичный результат уже сохранён.
        req_deadline = time.monotonic() + self._BATCH_REQUEST_BUDGET_S

        async def _attachment_text(att: Any, fname: str) -> tuple[str, bool, int]:
            """Возвращает (text, complete, pages_done) для одного вложения.
            complete=False означает, что OCR не дошёл до конца документа — фронт
            должен повторить разбор (авто-дораспознавание)."""
            kind = f"ocr:{att.id}"
            acc, cursor, complete = "", 0, False
            if ocr_cache is not None:
                try:
                    cached = await ocr_cache.get_result_cache(issue_external_id, kind)
                except Exception:
                    cached = None
                if cached:
                    d = cached.get("data") or {}
                    acc = d.get("text") or ""
                    cursor = int(d.get("next") or 0)
                    complete = bool(d.get("complete"))
            if complete:
                return acc, True, cursor
            # Не начинаем новую OCR-работу после дедлайна — отдаём что накопили
            # (complete=False → фронт дотянет следующим проходом).
            if time.monotonic() > req_deadline:
                return acc, False, cursor
            try:
                res = await self._okdesk.download_attachment(issue_external_id, att.id)
            except Exception:
                log.warning("analyze_batch_extract_failed", file=fname)
                return acc, complete, cursor
            if not res:
                return acc, complete, cursor
            try:
                # OCR/парсинг в потоке — не блокируем event loop (см. _enrich выше).
                frag, done, next_page = await asyncio.to_thread(
                    attachment_reader.extract_resumable, fname, res[0], cursor)
            except Exception:
                log.warning("analyze_batch_extract_failed", file=fname)
                return acc, complete, cursor
            acc = (acc + "\n" + frag).strip() if acc else (frag or "")
            if ocr_cache is not None:
                try:
                    await ocr_cache.save_result_cache(
                        issue_external_id, kind,
                        json.dumps({"text": acc, "next": next_page, "complete": done},
                                   ensure_ascii=False))
                except Exception:
                    log.warning("ocr_cache_save_failed", file=fname)
            return acc, done, next_page

        batch_atts = extractable[: self._BATCH_MAX_ATTACHMENTS]
        prog_done = 0       # вложений распознано полностью
        prog_pages = 0      # суммарно страниц распознано (курсоры)
        prog_complete = True
        for a in batch_atts:
            name = getattr(a, "attachment_file_name", None) or ""
            # Картинка из ПОДПИСИ письма (Outlook нумерует их image001.png,
            # image002.jpg …). Данных в ней нет, но OCR логотипа даёт достаточно
            # символов, чтобы пройти порог ниже, и заявка получала лишнюю строку
            # «Нет номера/даты» (62550, сессия C2, класс 19).
            if _SIGNATURE_IMAGE_RE.match(name.strip()):
                continue
            text, att_complete, att_pages = await _attachment_text(a, name)
            # Тип заявки. Если вызвавший его не посчитал (эндпоинт
            # /automate_batch зовёт нас напрямую, минуя parse_facts), определяем
            # сами и ПО ЭТОМУ документу: у письма-заявки на отключение вся суть
            # во вложении, в теме её может не быть вовсе.
            eff_intent = _intent_for(text)
            prog_pages += att_pages
            if att_complete:
                prog_done += 1
            else:
                prog_complete = False
            # Пустые/мусорные вложения (подпись письма image001.jpg → OCR в пару
            # символов) НЕ дают данных, но через title-fallback плодили ложный
            # объект «Нет номера/даты» (64657). Порог 15 символов отсекает шум.
            if not text or len(text.strip()) < 15:
                continue
            try:
                addr_m = re.search(r"по\s+адресу[:\s]+(.{5,120}?)(?:\s+и\s+состав|\s+наход|\.|$)", text, re.I | re.S)
                address = re.sub(r"\s+", " ", addr_m.group(1)).strip() if addr_m else None
                # Имя файла — надёжный источник гос.номера (в нём «…_с255но_КАМАЗ_…»).
                # В тексте год+«Не» давал ложный «2026НЕ».
                filename_plate = _parse(name).plate
            except Exception:
                log.warning("analyze_batch_parse_failed", file=name)
                continue

            # Сформировать цели (plate, date, sheet) для анализа.
            # Приоритет веток:
            # 1. Имя файла содержит гос.номер → один ТС, факты из всего текста.
            # 2. Сводное письмо с таблицей «Дата выезда» (63317) → каждый ТС
            #    получает СВОЮ дату из его строки, а не общую первую дату.
            # 3. Мульти-акт PDF (несколько «Акт №») → сегментация по актам (64250).
            # 4. Общая заявка со списком ТС → одна дата/ПЛ на всех.
            # targets: (plate, date, sheet_km(ПЛ от клиента), glonass_km(система от клиента)).
            targets: list[tuple[str, str | None, float | None, float | None]] = []
            # Моточасы строки по ключу (номер без региона, дата). Отдельная карта,
            # а не пятое поле `targets`: кортеж собирается в десятке ветвей ниже.
            hours_by_row: dict[tuple[str, str | None], float] = {}
            base_date: str | None = None
            tl = text.lower()
            # Признак «акта неисправности»: явный маркер ЛИБО сочетание пробега по
            # путевому/одометру и по ГЛОНАСС/ССМ у ТС (свободные акты Ульяновского).
            act_like = (("дата неисправности" in tl and "путево" in tl)
                        or (("одометр" in tl or "путево" in tl)
                            and ("глонас" in tl or "ссм" in tl or "смс" in tl)))
            # 64731/64850/64851: в одном PDF несколько актов/ТС, а в имени файла
            # перечислены все номера — ветка «номер из имени» брала только первый
            # и теряла остальные. Разделители _/- заменяем пробелом ТОЛЬКО в имени
            # файла (в тексте lookbehind защищает от «№ШР175 ОТ», 64144).
            # Считаем РАЗНЫЕ ТС по ключу без региона (_plate_dedup_key): номер с
            # регионом и без — один ТС (64513), а не повод уйти в мульти-ветку.
            fname_plates = extract_all_plates(name.replace("_", " ").replace("-", " "))
            if filename_plate:  # спец-формат (5297СУ) не ловится STD-регэкспом
                fname_plates = list(dict.fromkeys([filename_plate, *fname_plates]))
            acts_segments = _split_acts(text)
            # include_special: во вложениях/таблицах спецтехника (2874СЕ, АА8941)
            # — гейт _plate_special_ok отсекает времена/интервалы (65676: 2 ТС в
            # xlsx, раньше STD-регэксп давал [] → пакет находил лишь 1 из темы).
            text_plates = extract_all_plates(text, include_special=True)
            # «Акт №» в теле может быть просто ссылкой («на основании акта №12») —
            # мульти-акт только когда НЕСКОЛЬКО сегментов содержат свои номера.
            act_segs_with_plates = sum(1 for seg in acts_segments if extract_all_plates(seg))
            text_plate_keys = {_plate_dedup_key(p) for p in text_plates}
            fname_plate_keys = {_plate_dedup_key(p) for p in fname_plates}
            multi_doc = (len(fname_plate_keys) >= 2
                         or act_segs_with_plates >= 2
                         or len(text_plate_keys | fname_plate_keys) >= 2)
            if filename_plate and not multi_doc:
                p = _parse(name, extra=text)
                base_date = p.date
                targets.append((filename_plate, p.date, p.sheet_mileage_km, p.declared_system_km))
            elif re.search(r"дат[аы]\s+выезда", text, re.I):
                # Сводное письмо-таблица (Саратовские РС, 63317):
                # «Автомобиль, г/н | Дата выезда | Пробег по Глонасс | Пробег по 1С».
                summary_pairs = _parse_summary_table(text)
                for plate, pdate, glonass, sheet in summary_pairs:
                    # targets: (plate, date, sheet=ПЛ/1С, glonass=заявл. система)
                    targets.append((plate, pdate, sheet, glonass))
                if not targets:
                    p = _parse(name, extra=text)
                    base_date = p.date
                    for plate in text_plates:
                        targets.append((plate, p.date, p.sheet_mileage_km, p.declared_system_km))
            elif "пробег тс" in tl:
                # Табличный отчёт «Группировка <дата>» (Ульяновские РС, 64436):
                # строка — гос.номер + «Пробег ТС» (=ПЛ) + «Пробег по ГЛОНАСС» (система).
                p0 = _parse(name, extra=text)
                for plate, sheet_km, glonass_km, row_date, hours in _parse_grouping_table(text):
                    d = row_date or p0.date
                    targets.append((plate, d, sheet_km, glonass_km))
                    # Моточасы носим ОТДЕЛЬНОЙ картой, а не пятым полем кортежа:
                    # `targets` собирается в десятке ветвей выше и ниже, и
                    # расширение кортежа задело бы их все ради одной колонки.
                    if hours is not None:
                        hours_by_row[(_plate_dedup_key(plate) if plate else "", d)] = hours
                if not targets:
                    base_date = p0.date
                    for plate in text_plates:
                        targets.append((plate, p0.date, p0.sheet_mileage_km, p0.declared_system_km))
            elif act_like:
                # Акт(ы) неисправности. Многоактный PDF (Волжское, 64481): один
                # «Акт №» = один ТС. Если же «Акт №» нет, но в документе НЕСКОЛЬКО
                # номеров (Чапаевское «Общая»: один Word — список ТС) — раскладываем
                # по списку (_parse_body_vehicles), иначе потеряли бы всех кроме 1-го.
                rows = _parse_act_blocks(text)
                if len(rows) < 2 and len(text_plates) >= 2:
                    rows = _parse_body_vehicles(text)
                for plate, pdate, psheet, pglonass in rows:
                    targets.append((plate, pdate, psheet, pglonass))
                if not targets:
                    p = _parse(name, extra=text)
                    base_date = p.date
                    for plate in text_plates:
                        targets.append((plate, p.date, p.sheet_mileage_km, p.declared_system_km))
            else:
                acts = acts_segments
                if len(acts) >= 2:
                    for seg in acts:
                        seg_plates = extract_all_plates(seg)
                        if not seg_plates:
                            continue
                        sp = _parse(name, extra=seg)
                        for plate in seg_plates:
                            targets.append((plate, sp.date, sp.sheet_mileage_km, sp.declared_system_km))
                else:
                    p = _parse(name, extra=text)
                    base_date = p.date
                    plates = list(text_plates)
                    # Один документ — несколько ТС списком, без «Акт №» и без маркеров
                    # пробега (Чапаевское без явных пробегов): не терять остальные ТС.
                    if len(plates) >= 2:
                        bv = _parse_body_vehicles(text)
                        if len(bv) >= 2:
                            for plate, pdate, psheet, pglonass in bv:
                                targets.append((plate, pdate, psheet, pglonass))
                    # 64290: номер только в ТЕМЕ тикета (forward-письмо), не в PDF.
                    # НО только когда документ ОДИН: при нескольких вложениях со
                    # своими ТС номер из темы приписывался КАЖДОМУ файлу, чей OCR
                    # не прочитался (61292: наряд на Е677ВА73 получил Т185ТН73 из
                    # темы, дедуп по паре схлопнул его с настоящим Т185ТН73, и
                    # строка по третьему вложению пропала). Без темы такой файл
                    # честно станет строкой «Номер не распознан».
                    if not plates and issue_title and not multi_doc:
                        tp = _parse(issue_title).plate
                        if tp:
                            plates = [tp]
                    if not targets:
                        for plate in plates:
                            targets.append((plate, p.date, p.sheet_mileage_km, p.declared_system_km))

            # Страховка мульти-документа: номер перечислен в имени файла, но его
            # акт не распознался в OCR-тексте — добираем с датой документа, иначе
            # ТС молча пропадает из разбора (64851: А759РС после «111-»).
            if multi_doc and fname_plates:
                have = {_plate_dedup_key(pl) for pl, _, _, _ in targets if pl}
                for pl in fname_plates:
                    if _plate_dedup_key(pl) not in have:
                        # Дата None: ниже её заполнит дата ДОКУМЕНТА (имя файла/
                        # тема), а не дата чужого акта из этого же PDF.
                        targets.append((pl, None, None, None))

            # Дата документа/темы/ТЕЛА для объектов без своей даты (Чапаевское
            # «Общая»: дата одна в шапке/имени файла/теме, не у каждого ТС в
            # списке) — чтобы анализ телеметрии мог идти, а не упирался в «Нет
            # номера/даты». ТЕЛО заявки добавлено к теме: сводный разбор карточки
            # смотрит тему+описание, и когда дата стояла ТОЛЬКО в описании,
            # строки оставались без даты, хотя в шапке карточки дата была (65910).
            if any(d is None for _, d, _, _ in targets):
                doc_date = (_parse(name, extra=text).date
                            or (_parse(issue_title, issue_description).date
                                if (issue_title or issue_description) else None)
                            or fallback_date)
                if doc_date:
                    targets = [(p, d or doc_date, s, g) for p, d, s, g in targets]

            # Регион номера — из темы, ЕДИНЫМ местом для всех ветвей выше
            # (имя файла, таблицы, акты, страховка мульти-документа): иначе
            # усечённый номер из OCR/имени файла уходил в разбор без региона.
            targets = _restore_region(targets)

            # Год строк, пришедших из ТАБЛИЦ/АКТОВ (_parse_act_blocks,
            # _parse_summary_table, _parse_grouping_table, _parse_body_vehicles),
            # прижимаем к дате создания заявки в одном месте: эти парсеры берут
            # год «как написано», и опечатка клиента в годе (65975) уводила окно
            # телеметрии в пустоту. Без created_at — ни одной правки.
            if created is not None:
                targets = [(p, _clamp_year_to_created(d, created), s, g)
                           for p, d, s, g in targets]
                # Ключ карты моточасов содержит дату — клампим и его, иначе
                # моточасы перестали бы находиться у строк с поправленным годом.
                hours_by_row = {(k, _clamp_year_to_created(d, created)): v
                                for (k, d), v in hours_by_row.items()}

            if not targets:
                results.append({
                    "file": name, "plate": None, "date": base_date,
                    "sheet_mileage_km": None, "system_mileage_km": None,
                    "declared_system_km": None, "engine_hours": None,
                    "address": address, "flags": [], "teleport_jumps": 0,
                    "telemetry": None,
                    "verdict": (eff_intent and _verdict_for_intent(eff_intent)
                                or _missing_facts_verdict(None, base_date)),
                })
                continue

            # Дедуп по ПАРЕ (номер без региона, дата): один объект может иметь
            # несколько выездов по разным датам (63317/О579СХ) — каждую дату
            # разбираем отдельно; повторы той же пары (мульти-акт PDF, вариант
            # номера с регионом и без — 64513) отсекаем.
            seen_pairs: set[tuple[str, str | None]] = set()
            uniq: list[tuple[str | None, str | None, float | None, float | None]] = []
            for plate, pdate, psheet, pglonass in targets:
                # Строки без номера (OCR не прочитал, 64725) НЕ дедупим — каждый
                # нераспознанный акт виден отдельно; иначе несколько таких актов с
                # совпавшей датой схлопнулись бы в один по ключу ("", date).
                if not plate:
                    uniq.append((plate, pdate, psheet, pglonass))
                    continue
                key = (_plate_dedup_key(plate), pdate)
                if key in seen_pairs:
                    continue
                seen_pairs.add(key)
                uniq.append((plate, pdate, psheet, pglonass))

            # Параллельный разбор с ограничением конкуренции — иначе сотни
            # последовательных запросов телеметрии дают таймаут (63317).
            sem = asyncio.Semaphore(_BATCH_CONCURRENCY)

            async def _one(plate: str, pdate: str | None, psheet: float | None,
                           pglonass: float | None) -> dict[str, Any] | None:
                async with sem:
                    try:
                        return await self._analyze_object(
                            plate, pdate, psheet, address, name, declared=pglonass,
                            engine_hours=hours_by_row.get(
                                (_plate_dedup_key(plate) if plate else "", pdate)),
                            intent=eff_intent)
                    except Exception:
                        log.warning("analyze_batch_object_failed", file=name, plate=plate)
                        return None

            chunk = await asyncio.gather(*(_one(p, d, s, g) for p, d, s, g in uniq))
            results.extend(r for r in chunk if r is not None)
        # Глобальный дедуп по (номер без региона, дата) ПОВЕРХ всех вложений: один
        # и тот же ТС на одну дату мог прийти в РАЗНЫХ вложениях/актах либо как
        # вариант номера с регионом и без (64513). Строки без номера сохраняем.
        # Строка БЕЗ даты, у которой есть та же машина С датой, — артефакт
        # страховки мульти-документа (номер добран из имени файла с date=None),
        # а не отдельный выезд: 61292 давал три строки на два ТС — Т185ТН73 с
        # датой и он же без даты. Тот же приём уже применён в _parse_body_vehicles.
        dated_keys = {_plate_dedup_key(str(r.get("plate")))
                      for r in results if r.get("plate") and r.get("date")}
        final: list[dict[str, Any]] = []
        seen_final: set[tuple[str, str | None]] = set()
        for r in results:
            plate = r.get("plate")
            if not plate:
                final.append(r)
                continue
            if not r.get("date") and _plate_dedup_key(str(plate)) in dated_keys:
                continue
            key = (_plate_dedup_key(str(plate)), r.get("date"))
            if key in seen_final:
                continue
            seen_final.add(key)
            final.append(r)
        if progress_out is not None:
            progress_out.update({
                "complete": prog_complete,
                "attachments_total": len(batch_atts),
                "attachments_done": prog_done,
                "pages_done": prog_pages,
            })
        return final

    async def compose_aggregate_answer(self, objects: list[dict[str, Any]],
                                       company: str | None = None,
                                       prior: dict[str, dict] | None = None) -> str:
        """Compose ONE comprehensive, polite Russian answer for an aggregate
        (ОДКР) issue, grouping objects by verdict. No splitting into children.

        ``prior`` maps a normalized plate -> ``{category, answer, fault_date}``
        for vehicles that already received a resolved answer in a past issue.
        When provided, those prior answers are surfaced to the model so the new
        aggregate response stays consistent with what the client was told before.
        """
        # ДЕТЕРМИНИРОВАННАЯ группировка по фактическому вердикту (включая ручные
        # правки оператора). LLM здесь НЕ используем: он путал, какой ТС в какой
        # группе (64435 — относил машины не в свой вердикт). Группы строим в коде —
        # гарантирует, что гос.номер всегда в группе своего вердикта.
        phrasing = self._VERDICT_PHRASING
        order = list(phrasing.keys())
        groups: dict[str, list[str]] = {}
        for o in objects:
            plate = o.get("plate")
            verdict = o.get("verdict")
            if not plate or verdict in _SERVICE_VERDICTS or verdict not in phrasing:
                continue  # «Нет номера/даты», «Нет даты» и т.п. в сводку не включаем
            groups.setdefault(verdict, [])
            if plate not in groups[verdict]:
                groups[verdict].append(plate)
        if not groups:
            return ""
        # Без служебных ярлыков («Глушение:» и т.п. — это для специалистов): клиенту
        # отдаём связные фразы по группам. Группировка по вердикту — детерминированная.
        lines = ["Здравствуйте! По результатам сверки:"]
        for verdict in order:
            plates = groups.get(verdict)
            if plates:
                lines.append(f"По ТС {', '.join(plates)} {phrasing[verdict]}.")
        return "\n".join(lines)

    # Сколько строк разбора уходит в ОДИН запрос к модели. Больше — промпт
    # раздувается и модель начинает путать объекты местами (та же беда, что в
    # compose_aggregate_answer, где группировку пришлось вернуть в код).
    _AI_BATCH_MAX_OBJECTS = 25

    @staticmethod
    def _ai_row_facts(o: dict[str, Any]) -> dict[str, Any]:
        """Компактные факты одной строки разбора для промпта (по asdict(TelemetryFacts)).

        Полный набор метрик на 25 объектов не влезает в разумный промпт, поэтому
        берём то, на чём стоит лестница правил: пробеги, питание, спутники, разрывы.
        """
        t = o.get("telemetry") or {}
        return {
            "гос_номер": o.get("plate"),
            "дата": o.get("date"),
            "пробег_по_путевому_листу_км": o.get("sheet_mileage_km"),
            "моточасы_по_путевому_листу": o.get("engine_hours"),
            "пробег_заявленный_клиентом_км": o.get("declared_system_km"),
            "реальный_пробег_системы_км": o.get("system_mileage_km"),
            "мин_напряжение_В": t.get("min_power_v"),
            "доля_без_питания": t.get("power_off_ratio"),
            "среднее_спутников": t.get("avg_sat"),
            "доля_слабого_сигнала": t.get("low_sat_ratio"),
            "макс_разрыв_трека_мин": t.get("max_gap_min"),
            "телепортов_трека": t.get("teleport_jumps"),
            "пакетов_телеметрии": t.get("packets"),
            "макс_скорость": t.get("max_speed"),
            "дата_последнего_сообщения": t.get("last_message_date"),
            "признаки": o.get("flags") or [],
            "спецтехника": bool(o.get("spec_vehicle")),
            "вердикт_правил": o.get("verdict"),
            "подсказка_эвристики": o.get("heuristic_category"),
        }

    async def ai_batch_verdicts(self, objects: list[dict[str, Any]],
                                issue_title: str | None = None,
                                issue_description: str | None = None,
                                comments: str | None = None,
                                examples: list[dict[str, Any]] | None = None,
                                ) -> dict[str, Any]:
        """ОДИН платный вызов DeepSeek на ВСЮ мультиобъектную заявку.

        До этого шага строки разбора несли только вердикт правил: ``analyze_batch``
        считает ``_verdict_from_facts`` и не тратит токенов, а ``automate`` умеет
        оценивать лишь ОДИН ТС. Здесь модель получает факты всех строк разом и
        возвращает по каждой уверенность, обоснование и черновик ответа.

        Правки оператора (``verdict_source == "operator"``) в модель не уходят и не
        перезаписываются: ручное решение сильнее машины. Строки без телеметрии
        (объект не найден, номер не распознан) тоже пропускаем — модели нечего
        обосновывать, а выдумывать факты она не должна.

        Возвращает ``{"rows": {индекс: {...}}, "sent": n, "skipped": n, "note": str|None}``
        — вызывающий эндпоинт сам вливает это в кэш разбора.
        """
        eligible: list[tuple[int, dict[str, Any]]] = [
            (i, o) for i, o in enumerate(objects)
            if o.get("telemetry") and o.get("verdict_source") != "operator"
        ]
        skipped = len(objects) - len(eligible)
        if not eligible:
            return {"rows": {}, "sent": 0, "skipped": skipped,
                    "note": "Нечего отправлять в ИИ: у строк нет телеметрии либо "
                            "вердикты выставлены оператором вручную."}
        truncated = len(eligible) > self._AI_BATCH_MAX_OBJECTS
        batch = eligible[: self._AI_BATCH_MAX_OBJECTS]
        catalog = "\n".join(
            f"- {c['key']}: {c['when']}" for c in _CATEGORY_CATALOG
        )
        payload = [{"i": i, **self._ai_row_facts(o)} for i, o in batch]
        system = (
            "Ты — ассистент техподдержки GPSPOS. В заявке НЕСКОЛЬКО единиц техники: "
            "по каждой строке дан набор фактов телеметрии и предварительный вердикт, "
            "посчитанный правилами. Для КАЖДОЙ строки выбери категорию из каталога, "
            "оцени уверенность, объясни вывод и составь короткий ответ клиенту по этому ТС. "
            "Правила вывода: (1) если за дату ЕСТЬ пакеты — питание на терминале БЫЛО, "
            "«Не было питания» ставь только при реальной просадке напряжения или полном "
            "отсутствии данных; (2) напряжение в норме, но спутников нет — это ГЛУШЕНИЕ, "
            "а не потеря питания; (3) большой разрыв трека — сначала ищи признаки глушения "
            "(телепорты, потеря спутников), и только при чистом треке считай это "
            "буферизацией «Терминал подключился»; (4) спецтехнику по километрам не судят — "
            "для неё «Проверить», оценка по факту работы/моточасам. "
            "Вердикт правил — сильная подсказка: меняй его, только если факты прямо "
            "противоречат ему, и тогда объясни, ЧТО именно противоречит. "
            "Числа бери из фактов, ничего не выдумывай. Ответ клиенту — 1–3 предложения, "
            "с приветствием, с реальными датой и пробегом. "
            "Строку с полем \"i\" не пропускай и не переставляй местами: \"i\" — это "
            "идентификатор строки, ответ по каждому объекту обязан нести его же \"i\". "
            "Дополнительно составь ОДИН сводный ответ клиенту по всей заявке (поле "
            "\"summary\"): сгруппируй машины по причине, перечисли гос.номера каждой "
            "группы и объясни причину. Гос.номера бери ТОЛЬКО из данных — чужих не "
            "добавляй и не выдумывай. "
            "Верни СТРОГО JSON без пояснений: "
            '{"objects": [{"i": 0, "category": "...", "confidence": 0.0-1.0, '
            '"reasoning": "...", "answer": "..."}], "summary": "..."}'
        )
        head = f"Тема заявки: {issue_title or '—'}\n"
        body = _strip_html(issue_description)
        if body.strip():
            head += f"Текст заявки: {body[:1200]}\n"
        comments_block = ""
        if comments and comments.strip():
            ctext = comments.strip()
            if len(ctext) > 3000:
                ctext = ctext[:1200] + "\n…[середина переписки опущена]…\n" + ctext[-1800:]
            comments_block = f"\nКомментарии по заявке:\n{ctext}\n"
        user = (
            f"Каталог категорий:\n{catalog}\n\n"
            f"{head}{comments_block}"
            f"{self._format_examples(examples)}"
            f"\nСтроки разбора (JSON, по одной на объект):\n"
            f"{json.dumps(payload, ensure_ascii=False)}\n\n"
            f"Верни ответ по каждой из {len(batch)} строк, строго в JSON."
        )
        # Потолок ответа считаем от ЧИСЛА СТРОК: на каждую модель пишет категорию,
        # уверенность, обоснование и черновик клиенту, плюс один сводный текст на
        # всю заявку. С общим дефолтом (2048) ответ на 12 строк обрывался на
        # полуслове — JSON не парсился, и платный вызов уходил впустую (65915,
        # первый реальный прогон). ~260 токенов на строку с запасом на кириллицу.
        max_tokens = min(8192, 600 + 260 * len(batch))
        raw = await self._llm.chat(system, user, max_tokens=max_tokens)
        parsed = self._parse_llm_json(raw)
        items = parsed.get("objects") if isinstance(parsed, dict) else None
        if not isinstance(items, list):
            # Сбой связи и «модель ответила не то» лечатся по-разному: первое —
            # повторить, второе — править промпт. Раньше обе беды давали один текст.
            if raw == LLM_ERROR_TEXT:
                note = ("Не удалось связаться с ИИ — вердикты правил оставлены "
                        "без изменений. Попробуйте ещё раз.")
            else:
                note = ("Модель вернула ответ в неожидаемом формате — вердикты "
                        "правил оставлены без изменений.")
            log.warning("ai_batch_unparsable", issue=issue_title,
                        rows=len(batch), max_tokens=max_tokens,
                        raw_len=len(raw or ""), raw_tail=(raw or "")[-300:])
            return {"rows": {}, "sent": len(batch), "skipped": skipped, "note": note}
        allowed_idx = {i for i, _ in batch}
        rows: dict[int, dict[str, Any]] = {}
        for it in items:
            if not isinstance(it, dict):
                continue
            try:
                idx = int(it.get("i"))
            except (TypeError, ValueError):
                continue
            if idx not in allowed_idx:
                continue  # модель придумала строку, которой не давали
            category = str(it.get("category") or "").strip()
            if category not in _AI_ROW_VERDICTS:
                # Категория вне каталога — вердикт правил надёжнее выдумки модели,
                # но обоснование и черновик всё равно полезны.
                category = ""
            try:
                conf = float(it.get("confidence"))
            except (TypeError, ValueError):
                conf = 0.0
            rows[idx] = {
                "verdict": category or None,
                "confidence": max(0.0, min(1.0, conf)),
                "reasoning": (str(it.get("reasoning") or "").strip() or None),
                "draft_answer": _clean_answer(it.get("answer")),
            }
        note = None
        if truncated:
            note = (f"ИИ разобрал первые {len(batch)} объектов из {len(eligible)} — "
                    f"остальные строки остались с вердиктом правил.")
        # Сводный ответ от модели проверяем КОДОМ: она уже путала, какой ТС в какой
        # группе (64435). Упомянула номер, которого в заявке нет → текст выбрасываем,
        # у оператора остаётся сводный ответ по правилам. Лучше без текста, чем с
        # чужой машиной в письме клиенту.
        summary = str(parsed.get("summary") or "").strip()
        summary_note: str | None = None
        if summary:
            known = {_plate_dedup_key(str(o.get("plate")))
                     for o in objects if o.get("plate")}
            mentioned = {_plate_dedup_key(p) for p in extract_all_plates(summary,
                                                                        include_special=True)}
            alien = mentioned - known
            if alien:
                log.warning("ai_summary_alien_plates", alien=sorted(alien))
                summary, summary_note = "", (
                    "Сводный ответ ИИ отброшен: в тексте оказались гос.номера, которых нет "
                    "в заявке. Используйте сводный ответ по правилам.")
        return {"rows": rows, "sent": len(batch), "skipped": skipped, "note": note,
                "summary": _clean_answer(summary) if summary else None,
                "summary_note": summary_note}

    # Формулировки вердиктов для ответа клиенту БЕЗ модели. Один источник для
    # сводного ответа (compose_aggregate_answer) и для ответа по одному ТС.
    _VERDICT_PHRASING: dict[str, str] = {
        "Данные верны": "сбоев не обнаружено, данные корректны",
        "Терминал подключился": "терминал временно терял связь, данные позже догрузились, пробег сошёлся",
        "Глушение": "в указанный период фиксировалось воздействие средств подавления GPS-сигнала (глушение), из-за чего данные трека искажены/занижены",
        "Не было питания": "отсутствовало питание терминала в указанную дату (трек за период отсутствует)",
        "Изменили настройки": "скорректированы настройки детектора поездок, пробег отобразился полностью",
        "Проверить": "требуется дополнительная проверка",
        "Нет данных": "данные отсутствуют — требуется удалённая проверка силами нашей техподдержки",
        "Диагностика": "данные отсутствуют — требуется удалённая проверка силами нашей техподдержки",
        "Объект не найден": "объект не найден в системе мониторинга",
    }

    def rules_answer_for_object(self, obj: dict[str, Any]) -> str:
        """Ответ клиенту по ОДНОМУ объекту БЕЗ модели — шаблон его категории.

        Берём готовый текст из ``_CATEGORY_CATALOG`` и подставляем дату и реальный
        пробег: это ровно то, что оператор писал руками до появления ИИ. Категории
        вне каталога («Проверить», «Нет данных», …) шаблона не имеют — для них
        собираем фразу из ``_VERDICT_PHRASING``, чтобы ответ был всегда.
        """
        verdict = str(obj.get("verdict") or "")
        plate = obj.get("plate") or "—"
        if verdict in _SERVICE_VERDICTS:
            # Служебный ярлык («Нет даты», «Номер не распознан», …) — это НЕ
            # причина расхождения, а сообщение оператору. В текст клиенту такой
            # ярлык просачиваться не должен ни через каталог, ни через фразы.
            return (f"Здравствуйте! По ТС {plate} не удалось однозначно определить причину "
                    "расхождения по имеющимся данным. Уточните, пожалуйста, гос.номер и дату.")
        iso = str(obj.get("date") or "")
        date = _iso_to_ru(iso) or iso or "указанную дату"
        system = obj.get("system_mileage_km")
        system_km = ("—" if system is None
                     else str(int(round(float(system)))))
        tpl = next((c["template"] for c in _CATEGORY_CATALOG if c["key"] == verdict), None)
        if tpl:
            return tpl.replace("{date}", date).replace("{system_km}", system_km)
        phrase = self._VERDICT_PHRASING.get(verdict)
        if phrase:
            return (f"Здравствуйте! По ТС {plate} за {date} {phrase}. "
                    "При необходимости уточним детали.")
        # Вердикта нет вообще (нет номера/даты, ошибка данных) — ответ клиенту
        # выдумывать нельзя, честно просим уточнить данные.
        return (f"Здравствуйте! По ТС {plate} не удалось однозначно определить причину "
                "расхождения по имеющимся данным. Уточните, пожалуйста, гос.номер и дату.")

    async def _analyze_object(self, plate: str, date: str | None, sheet: float | None,
                              address: str | None, file: str,
                              declared: float | None = None,
                              engine_hours: float | None = None,
                              intent: str | None = None) -> dict[str, Any]:
        item: dict[str, Any] = {
            "file": file, "plate": plate, "date": date,
            # sheet — пробег по путевому листу (ПЛ) от клиента; declared — пробег по
            # системе ГЛОНАСС со слов клиента (то, что он видит в ПК); system — РЕАЛЬНЫЙ
            # пробег из телеметрии geo.gpspos.ru (ниже).
            "sheet_mileage_km": sheet, "declared_system_km": declared,
            # Моточасы по ПЛ — отдельно от километров, в лестницу вердиктов не идут
            # (спецтехника как и раньше остаётся «Проверить»), но видны оператору.
            "engine_hours": engine_hours,
            "system_mileage_km": None,
            "address": address, "flags": [], "teleport_jumps": 0,
            # Полная телеметрия объекта (как в одиночном анализе, asdict(TelemetryFacts))
            # — фронт показывает её для выбранной строки таблицы. None, пока объект не
            # разобран (нет номера/даты) или телеметрия не собралась.
            "telemetry": None,
            "spec_vehicle": _is_special_vehicle(plate, file),
            # Ярлык «о чём заявка» рядом со строкой: оператор должен видеть, ПОЧЕМУ
            # строка вышла из пробеговой лестницы, а не только служебный вердикт.
            "issue_intent": intent,
            "verdict": _missing_facts_verdict(plate, date),
            # Вердикт строки получен ПРАВИЛАМИ (детерминированно, без DeepSeek).
            # Оператор может переписать его через /batch/verdict — тогда рядом
            # проставляется verdict_edited=True.
            "verdict_source": "rules",
            # Вторая, более простая эвристика (та, что уходит в LLM как hint) —
            # наружу, чтобы было видно расхождение двух детерминированных оценок.
            "heuristic_category": None,
        }
        # Заявка не о пробеге — ярлык типа информативнее, чем «Нет даты»: даты
        # неисправности в заявке на установку/отключение и не должно быть.
        if intent:
            item["verdict"] = _verdict_for_intent(intent)
        # Ярлык «чего не хватает» уже проставлен выше (_missing_facts_verdict):
        # акт распознан, но OCR не прочитал номер (64725) → «Номер не распознан»;
        # номер есть, а даты в заявке нет (65781) → «Нет даты».
        if plate and date:
            try:
                t = await self.gather_telemetry(plate, date)
                item["system_mileage_km"] = t.system_mileage_km
                item["flags"] = t.flags
                item["teleport_jumps"] = t.teleport_jumps
                # Плоские поля выше оставлены как есть (на них завязаны фронт и кэш),
                # telemetry — полный набор метрик для панели телеметрии по строке.
                item["telemetry"] = asdict(t)
                item["verdict"] = self._verdict_from_facts(
                    t, sheet, declared, bool(item["spec_vehicle"]), intent=intent)
                item["heuristic_category"] = self._heuristic_category(
                    ParsedIssue(plate=plate, date=date, sheet_mileage_km=sheet), t)
            except Exception:
                item["verdict"] = "Ошибка данных"
        return item

    @staticmethod
    def _verdict_from_facts(t: TelemetryFacts, sheet: float | None,
                            declared: float | None, spec_vehicle: bool,
                            intent: str | None = None) -> str:
        """ДЕТЕРМИНИРОВАННАЯ лестница вердиктов по фактам телеметрии (без LLM).

        Вынесена из ``_analyze_object`` без изменения порядка правил, чтобы тот же
        вердикт можно было получить по УЖЕ собранной телеметрии (см. ``rules_row``).
        """
        system = t.system_mileage_km
        # Заявка не о пробеге (установка/замена/отключение/перемещение) — вся
        # лестница ниже к ней неприменима: она отвечала бы на незаданный вопрос.
        # Телеметрия при этом СОБРАНА и видна оператору справкой (решение
        # пользователя, интервью 2): по ней видно, ожил ли объект после монтажа.
        if intent:
            return _verdict_for_intent(intent)
        # Order matters: jamming/power-off take precedence over a mileage
        # match (spoofing makes the track unreliable even if mileage coincides).
        if "object_not_found" in t.flags:
            return "Объект не найден"
        if "no_data" in t.flags:
            return "Нет данных"
        if "power_off" in t.flags:
            return "Не было питания"
        if "sparse_data" in t.flags:
            # Пакетов за сутки — единицы. Любой вердикт (и «Глушение», и «Данные
            # верны») был бы построен на данных, которых нет. Разворачиваем в
            # «Проверить»: вероятна неисправность терминала или демонтаж.
            return "Проверить"
        if spec_vehicle:
            # Спецтехника: км-вердикт (Глушение/Данные верны) ненадёжен —
            # данные есть, оценивать по факту работы/моточасам вручную.
            return "Проверить"
        if "jamming" in t.flags:
            return "Глушение"
        if sheet and system is not None and abs(sheet - system) <= max(5.0, sheet * 0.1):
            return "Данные верны"
        if (declared is not None and system is not None and sheet
                and abs(declared - system) <= max(5.0, system * 0.1)):
            # Ветка НАМЕРЕННО не утверждает «Данные верны» — не восстанавливать.
            #
            # Изначально (63317) логика была такая: телеметрия сходится с тем, что
            # клиент видит в системе, расходится только его ПЛ — значит проблема в
            # учёте клиента, данные мониторинга верны. Но это подмена вопроса:
            # совпадение «заявлено ≈ система» доказывает лишь, что клиент ПРАВИЛЬНО
            # ПРОЧИТАЛ наш экран. Жалоба-то на разрыв ПЛ↔система, и на него ветка
            # не отвечает — она молча назначала причиной учёт клиента.
            #
            # Проверка на 27 боевых заявках из training_samples, где ветка реально
            # срабатывает: из 9 вердиктов «Данные верны» ЛОЖНЫ 4 — 64873 (ПЛ 61 при
            # системе 3.3, оператор ответил про глушение), 64185 и 64181 (тоже
            # глушение), 65268 (не было питания). 44% ложных закрытий на ветке,
            # которая ведёт к автоответу клиенту.
            #
            # Поэтому здесь «Проверить» — честное «мы не знаем, посмотри глазами».
            # Цена решения: теряем ~5 верных автоответов из 27 (там оператор писал
            # «сбоев не обнаружено»), зато не закрываем 4 заявки неверно.
            return "Проверить"
        if (declared is not None and system is not None and sheet
                and system - declared > max(5.0, system * 0.25)
                and abs(sheet - system) <= max(5.0, sheet * 0.25)):
            # Клиент видит в системе заметно меньше, чем реально есть в
            # телеметрии, а реальный пробег уже примерно сошёлся с ПЛ —
            # данные догрузились позже (чёрный ящик). Если же system всё
            # ещё далёк от ПЛ — это «Проверить», а не ложное «догрузилось».
            return "Терминал подключился"
        return "Проверить"

    def rules_row(self, parsed: ParsedIssue, t: TelemetryFacts,
                  file: str = "(из текста заявки)",
                  intent: str | None = None) -> dict[str, Any]:
        """Строка разбора из УЖЕ собранной телеметрии — БЕЗ сетевых вызовов.

        Формат идентичен строкам ``analyze_batch``/``_analyze_object`` (фронт
        рисует одну и ту же таблицу для 1 и для N объектов).
        """
        spec = _is_special_vehicle(parsed.plate, file)
        has_facts = bool(parsed.plate and parsed.date)
        return {
            "file": file, "plate": parsed.plate, "date": parsed.date,
            "sheet_mileage_km": parsed.sheet_mileage_km,
            "declared_system_km": parsed.declared_system_km,
            "engine_hours": parsed.engine_hours,
            "system_mileage_km": t.system_mileage_km,
            "address": None, "flags": list(t.flags), "teleport_jumps": t.teleport_jumps,
            "telemetry": asdict(t) if has_facts else None,
            "spec_vehicle": spec,
            "verdict": (self._verdict_from_facts(
                t, parsed.sheet_mileage_km, parsed.declared_system_km, spec,
                intent=intent)
                if has_facts else (intent and _verdict_for_intent(intent)
                                   or _missing_facts_verdict(parsed.plate, parsed.date))),
            "verdict_source": "rules",
            "heuristic_category": (self._heuristic_category(parsed, t)
                                   if has_facts else None),
        }

    @staticmethod
    def _facts_payload(parsed: dict[str, Any], objects: list[dict[str, Any]],
                       spec_vehicle: bool = False,
                       needs_remote_diagnostics: bool = False,
                       ocr_progress: dict[str, Any] | None = None) -> dict[str, Any]:
        """Единый формат ответа детерминированного разбора (kind ``parse``).

        ``objects`` — строки разбора (1 или N, один и тот же движок). Сводные
        поля дублируют первую строку: одиночной карточке не нужно лезть в массив.
        """
        first = objects[0] if len(objects) == 1 else None
        payload: dict[str, Any] = {
            "parsed": parsed,
            "objects": objects,
            "total": len(objects),
            "jamming_count": sum(1 for o in objects if o.get("verdict") == "Глушение"),
            "ok_count": sum(1 for o in objects if o.get("verdict") == "Данные верны"),
            "telemetry": (first or {}).get("telemetry") if first else None,
            "verdict": (first or {}).get("verdict") if first else None,
            "heuristic_category": (first or {}).get("heuristic_category") if first else None,
            "verdict_source": "rules",
            "spec_vehicle": spec_vehicle,
            "needs_remote_diagnostics": needs_remote_diagnostics,
        }
        if ocr_progress is not None:
            payload["ocr_progress"] = ocr_progress
        return payload

    def client_comment_faults(
        self, client_comments: list[tuple[str, str]] | None,
    ) -> list[tuple[str, float | None, float | None, float | None]]:
        """Жалобы, дописанные КЛИЕНТОМ в переписке: ``(дата, ПЛ, система, м/ч)``.

        Вторая жалоба в комментарии — ОТДЕЛЬНЫЙ случай, а не уточнение первого:
        65918 — тело «Расхождение за 27.07 Пробег по пут,л 96км», комментарий
        клиента от 30.07 «Расхождение за 29.07 Пробег по пут.л 69км». У каждой
        даты своя телеметрия и свой вердикт, поэтому вторая жалоба заслуживает
        своей строки разбора, а не молчаливой потери.

        Берём только комментарии с числом км ЛИБО фразой-признаком (тот же гейт,
        что в ``_scan_comment_for_new_date``) — иначе «спасибо, ждём» дало бы
        строку по случайному числу. Каждый комментарий разбираем ТЕМ ЖЕ
        ``parse_issue`` с ``created_at`` = датой комментария: год даты без года
        берётся по ней, а «будущие» даты уже вырезаны ``_drop_dates_after``.
        Никогда не бросает: пустой список — просто нет дополнительных жалоб.
        """
        out: list[tuple[str, float | None, float | None, float | None]] = []
        for raw_date, text in client_comments or []:
            if not text or not text.strip():
                continue
            if not (_COMMENT_MILEAGE_RE.search(text) or _COMMENT_FAULT_RE.search(text)):
                continue
            limit = _created_date(raw_date)
            if limit is None:
                continue  # без даты комментария правило «не позже» не проверить
            try:
                p = self.parse_issue(None, _drop_dates_after(text, limit), None,
                                     created_at=limit)
            except Exception:  # pragma: no cover - разбор комментария best-effort
                continue
            if not p.date:
                continue
            pd = _created_date(p.date)
            if pd is None or pd > limit:
                continue
            out.append((p.date, p.sheet_mileage_km, p.declared_system_km,
                        p.engine_hours))
        return out

    async def _append_client_comment_rows(
        self, objects: list[dict[str, Any]],
        client_comments: list[tuple[str, str]] | None,
    ) -> list[dict[str, Any]]:
        """Добавить строки разбора по жалобам из клиентских комментариев (B3).

        Только когда в заявке ОДИН ТС: у мульти-ТС заявки непонятно, к какой
        машине относится дата из переписки, и строка вышла бы наугад (65847).
        Дедуп по паре (номер без региона, дата) — как в ``analyze_batch``.
        """
        plates = {_plate_dedup_key(str(o.get("plate"))): str(o.get("plate"))
                  for o in objects if o.get("plate")}
        if len(plates) != 1:
            return objects
        plate = next(iter(plates.values()))
        have = {(_plate_dedup_key(str(o.get("plate") or "")), o.get("date"))
                for o in objects}
        extra: list[dict[str, Any]] = []
        for date, sheet, declared, hours in self.client_comment_faults(client_comments):
            key = (_plate_dedup_key(plate), date)
            if key in have:
                continue
            have.add(key)
            try:
                extra.append(await self._analyze_object(
                    plate, date, sheet, None, "(из комментария клиента)",
                    declared=declared, engine_hours=hours))
            except Exception:  # pragma: no cover - телеметрия best-effort
                log.warning("comment_row_failed", plate=plate, date=date)
        return objects + extra

    async def parse_facts(self, issue_external_id: int,
                          title: str | None, description: str | None,
                          params: list[dict[str, Any]] | None = None,
                          attachments: list[Any] | None = None,
                          attachments_text: str | None = None,
                          comments: str | None = None,
                          plate_override: str | None = None,
                          date_override: str | None = None,
                          ocr_cache: Any = None,
                          progress_out: dict[str, Any] | None = None,
                          created_at: str | _dt.date | None = None,
                          client_comments: list[tuple[str, str]] | None = None,
                          ) -> dict[str, Any]:
        """ДЕТЕРМИНИРОВАННЫЙ разбор заявки: факты + предварительный вердикт.

        Ни одного обращения к DeepSeek: только regex-парсер, телеметрия из гео и
        лестница правил ``_verdict_from_facts``. ``attachments=None`` (по умолчанию)
        — вложения НЕ читаются и OCR не запускается; список вложений передаёт
        только «кнопочный» разбор, который сознательно платит за OCR.

        ``client_comments`` — комментарии КЛИЕНТА как ``(дата ISO, текст)``.
        Отдельно от строкового ``comments`` (дайджеста всей переписки для модели),
        потому что дату/пробег неисправности брать можно ТОЛЬКО из слов клиента и
        только не позже его сообщения (65781). Не передали — прежнее поведение.
        """
        parse_extra = attachments_text
        if comments and not _strip_html(description).strip():
            # 64871: у форвард-писем тело письма лежит в первом комментарии.
            parse_extra = _extra_with_comments(attachments_text, comments)
        parsed = self.parse_issue(title, description, params, extra_text=parse_extra,
                                  created_at=created_at)
        # Тот же текст, что видела шапка разбора, отдаём построчному движку —
        # иначе строка таблицы остаётся без даты, хотя в шапке дата есть.
        batch_extra = parse_extra
        # Текст для ДОБОРА ДАТЫ: только слова клиента, без «будущих» дат.
        # Передали client_comments (даже пустым списком) — верим им, а не полному
        # дайджесту: пустой список значит «клиент в переписке ничего не писал».
        comments_for_dates = (_client_comments_text(client_comments)
                              if client_comments is not None else comments)
        if comments_for_dates and not parsed.date:
            # Дата дописана КОММЕНТАРИЕМ при непустом описании (65780, см. такой
            # же добор в analyze_issue): комментарии добирают только ПУСТУЮ дату.
            extra_c = _extra_with_comments(parse_extra, comments_for_dates)
            alt = self.parse_issue(title, description, params,
                                   extra_text=extra_c, created_at=created_at)
            if alt.date:
                parsed.date, parsed.date_to = alt.date, alt.date_to
                # Найденную дату отдаём строкам ОТДЕЛЬНЫМ параметром, а не
                # подмешиванием переписки в текст: иначе построчный движок заводит
                # ТС по гос.номеру из ответа оператора и склеивает его с датой из
                # комментария про другую машину (65847). Дата — общая на заявку,
                # список машин — нет.
        if plate_override:
            norm = _normalize_plate(plate_override)
            parsed.plate = norm or plate_override.strip()
        if date_override:
            parsed.date = date_override.strip()
        spec = _is_special_vehicle(
            parsed.plate, f"{title or ''} {_strip_html(description)} {attachments_text or ''}")
        # Тема/описание наравне с комментариями — см. _client_awaiting_remote_diag.
        awaiting_diag = _client_awaiting_remote_diag(
            comments, title, _strip_html(description))
        parsed_out = asdict(parsed)
        parsed_out["plate_format_suspect"] = _plate_format_suspect(parsed.plate)
        # О чём заявка. Считаем ОДИН раз на всю заявку и отдаём строкам: тип
        # задаётся текстом заявки, а не отдельным ТС в списке. Пробеги уже
        # разобраны — если клиент назвал километры, тип не применяем.
        intent = _detect_non_mileage_intent(
            f"{title or ''}\n{_strip_html(description)}",
            attachments_text,
            has_mileage_facts=(parsed.sheet_mileage_km is not None
                               or parsed.declared_system_km is not None))
        # Обнуление ложного пробега проверяем ОТДЕЛЬНО от типа заявки: там
        # километры в тексте есть, и общий ограничитель has_mileage_facts
        # заглушил бы ярлык.
        if _detect_false_mileage(f"{title or ''} {_strip_html(description)}"):
            intent = FALSE_MILEAGE_INTENT
        parsed_out["issue_intent"] = intent

        objects: list[dict[str, Any]] = []
        if plate_override or date_override:
            # Ручная правка оператора важнее любого авто-разбора текста: одна
            # строка строго по заданным номеру/дате.
            objects = [await self._analyze_object(
                parsed.plate or "", parsed.date, parsed.sheet_mileage_km, None,
                "(из текста заявки)", declared=parsed.declared_system_km,
                engine_hours=parsed.engine_hours, intent=intent)]
        else:
            try:
                objects = await self.analyze_batch(
                    issue_external_id, attachments or [],
                    issue_title=title, issue_description=description,
                    ocr_cache=ocr_cache, progress_out=progress_out,
                    created_at=created_at, extra_text=batch_extra,
                    fallback_date=parsed.date, issue_intent=intent)
            except Exception:  # pragma: no cover - analyze_batch и так best-effort
                log.warning("parse_facts_batch_failed", issue=issue_external_id)
                objects = []
        if not objects and parsed.plate:
            # Парсер тела/темы номер нашёл, а построчный движок — нет
            # (нестандартная разметка): всё равно отдаём одну строку.
            objects = [await self._analyze_object(
                parsed.plate, parsed.date, parsed.sheet_mileage_km, None,
                "(из текста заявки)", declared=parsed.declared_system_km,
                engine_hours=parsed.engine_hours, intent=intent)]
        # Одна строка — синхронизируем сводный parsed с тем, что реально разобрано
        # (номер/дата могли прийти из построчного разбора тела, а не из parse_issue).
        if len(objects) == 1:
            row = objects[0]
            if not parsed_out.get("plate") and row.get("plate"):
                parsed_out["plate"] = row.get("plate")
                parsed_out["plate_format_suspect"] = _plate_format_suspect(row.get("plate"))
            if not parsed_out.get("date") and row.get("date"):
                parsed_out["date"] = row.get("date")
            # Моточасы построчный движок не носит (его строки — кортежи из
            # четырёх полей), а из тела заявки они разобраны: у одиночной
            # заявки строка описывает тот же ТС, что и шапка, — переносим,
            # иначе оператор моточасов не увидит (64742: «по 1С 7км(моточасы)»).
            if row.get("engine_hours") is None and parsed.engine_hours is not None:
                row["engine_hours"] = parsed.engine_hours
        # Вторая жалоба клиента в переписке — ОТДЕЛЬНАЯ строка разбора (65918).
        # После синхронизации шапки: шапка описывает жалобу ИЗ ТЕЛА заявки.
        if client_comments and not (plate_override or date_override):
            objects = await self._append_client_comment_rows(objects, client_comments)
        payload = self._facts_payload(
            parsed_out, objects, spec_vehicle=spec,
            needs_remote_diagnostics=awaiting_diag,
            ocr_progress=progress_out if attachments else None)
        # Жалоба «за месяц и в процентах» без конкретного дня (65886): месячный
        # отчёт мы не считаем (решение пользователя, интервью 2), но сухое
        # «Нет даты» не объясняет оператору, ЧЕГО не хватает и почему.
        if (not any(o.get("date") for o in objects)
                and _is_monthly_percent_complaint(
                    f"{title or ''} {_strip_html(description)}")):
            payload["note"] = (
                "Жалоба сформулирована за МЕСЯЦ и в процентах, конкретной даты "
                "неисправности в заявке нет. Для разбора нужен день: уточните дату "
                "у клиента или задайте её вручную.")
        return payload

    async def build_training_sample(
        self, title: str | None, description: str | None,
        operator_answer: str, final_status: str,
        created_at: str | _dt.date | None = None,
    ) -> dict[str, Any] | None:
        """Build a (telemetry facts → operator decision) sample for later AI training.

        Best-effort: returns None if the issue isn't a parseable mileage ticket.
        Never raises — callers log decisions, they must not fail on this.
        """
        parsed = self.parse_issue(title, description, None, created_at=created_at)
        if not parsed.plate or not parsed.date:
            return None
        telemetry = TelemetryFacts()
        try:
            telemetry = await self.gather_telemetry(parsed.plate, parsed.date, parsed.date_to)
        except Exception:  # pragma: no cover - best effort
            log.warning("training_sample_telemetry_failed", plate=parsed.plate)
        return {
            "issue_title": title,
            "issue_description": description,
            "plate": parsed.plate,
            "fault_date": parsed.date,
            "mileage_sheet_km": parsed.sheet_mileage_km,
            "mileage_system_km": telemetry.system_mileage_km,
            "telemetry_json": json.dumps(asdict(telemetry), ensure_ascii=False),
            "operator_answer": operator_answer,
            "final_status": final_status,
        }

    def to_dict(self, r: AutomationResult) -> dict[str, Any]:
        parsed = asdict(r.parsed)
        # Флаг для UI: номер не соответствует формату (опечатка клиента, 64868) —
        # оператор увидит явную пометку и сможет исправить номер вручную.
        parsed["plate_format_suspect"] = _plate_format_suspect(r.parsed.plate)
        return {
            "parsed": parsed,
            "telemetry": asdict(r.telemetry),
            "category": r.category,
            "confidence": r.confidence,
            "draft_answer": r.draft_answer,
            "reasoning": r.reasoning,
            "needs_review": r.needs_review,
            "error": r.error,
            "needs_remote_diagnostics": r.needs_remote_diagnostics,
            "spec_vehicle": r.spec_vehicle,
            "auto_eligible": r.auto_eligible,
            # Чем получена category ("rules"/"ai") и что сказала эвристика.
            "verdict_source": r.verdict_source,
            "heuristic_category": r.heuristic_category,
        }

    def facts_dict(self, r: AutomationResult) -> dict[str, Any]:
        """Детерминированный СРЕЗ полного разбора — то же, что отдаёт parse_facts.

        Нужен, чтобы после полного прогона (``automate``) факты легли в кэш
        ``parse`` БЕЗ повторного обращения к телеметрии: они переживут следующую
        инвалидацию ИИ-результата и отдадутся фронту бесплатно.
        """
        parsed = asdict(r.parsed)
        parsed["plate_format_suspect"] = _plate_format_suspect(r.parsed.plate)
        # Строку строим ТОЛЬКО когда телеметрия реально собиралась. У общего
        # (не-пробегового) пути TelemetryFacts пустой — без флагов и пакетов
        # лестница правил выдала бы бессмысленное «Проверить».
        t = r.telemetry
        has_telemetry = bool(t.packets or t.flags or t.system_mileage_km is not None)
        rows = ([self.rules_row(r.parsed, t)]
                if (r.parsed.plate and r.parsed.date and has_telemetry) else [])
        return self._facts_payload(parsed, rows, spec_vehicle=r.spec_vehicle,
                                   needs_remote_diagnostics=r.needs_remote_diagnostics)
